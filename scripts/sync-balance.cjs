#!/usr/bin/env node
/**
 * Brings the planning room's balance numbers into the game (D-073).
 *
 * The source of truth lives outside this repo, in the planning room's
 * balance calculator (`_design/tools/balance`, served at home.ribs.kr:3107):
 *   - balance.json → libs/games/roguelite/src/lib/growth/balance.generated.ts (the game's
 *     copy, a module like the generated maps — the lib can't import JSON from outside src)
 *   - calc.js      → libs/games/roguelite/src/test-support/balance-calc.cjs (the
 *     tests' expected values: the engine's formulas must give what the calculator gives)
 *
 * Usage: npm run sync-balance [-- <path to the balance folder>]
 */
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const from = path.resolve(process.argv[2] ?? path.join(repo, '..', '_design', 'tools', 'balance'));
const dataOut = path.join(repo, 'libs/games/roguelite/src/lib/growth/balance.generated.ts');
const calcOut = path.join(repo, 'libs/games/roguelite/src/test-support/balance-calc.cjs');

const data = JSON.parse(fs.readFileSync(path.join(from, 'balance.json'), 'utf8'));
if (!data.globals || !Array.isArray(data.skills) || data.skills.length === 0) {
  throw new Error(`${from}/balance.json: expected { globals, skills: [...] }`);
}
fs.writeFileSync(
  dataOut,
  `// GENERATED by scripts/sync-balance.cjs from the planning room's balance.json — do not edit here.
// Change the numbers in their calculator (home.ribs.kr:3107), then run \`npm run sync-balance\`.
export const BALANCE_JSON: unknown = ${JSON.stringify(data, null, 2)};
`,
);

const calc = fs.readFileSync(path.join(from, 'calc.js'), 'utf8').replace(/\r\n/g, '\n');
fs.mkdirSync(path.dirname(calcOut), { recursive: true });
fs.writeFileSync(
  calcOut,
  `// GENERATED by scripts/sync-balance.cjs from the planning room's calc.js — do not edit here.\n// The engine's growth formulas are tested against this (see src/lib/growth/*.spec.ts).\n${calc}`,
);
console.log(`synced ${data.skills.length} skills (balance.json v${data.version}, updated ${data.updated}) from ${from}`);
